#!/usr/bin/env bash
# Writes Cloudflare's current IP ranges into two nginx snippets used by
# deploy/nginx-nitsdate-cloudflare.conf, then reloads nginx. Run as root:
#   sudo deploy/cloudflare-ips.sh
# Cloudflare rarely changes these ranges; rerun if they announce a change.
set -euo pipefail

v4=$(curl -fsS -m 20 https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS -m 20 https://www.cloudflare.com/ips-v6)
ranges=$(printf '%s\n%s\n' "$v4" "$v6" | grep -E '^[0-9a-f:.]+/[0-9]+$')
[ "$(wc -l <<<"$ranges")" -ge 10 ] || { echo "unexpected Cloudflare IP list" >&2; exit 1; }

dir=/etc/nginx/snippets
mkdir -p "$dir"
{
  echo "# generated by cloudflare-ips.sh on $(date -u +%F): take the visitor's IP from Cloudflare's header"
  sed 's/.*/set_real_ip_from &;/' <<<"$ranges"
  echo "real_ip_header CF-Connecting-IP;"
} > "$dir/cloudflare-realip.conf"
{
  echo "# generated by cloudflare-ips.sh on $(date -u +%F): body of a geo block, 1 = connection came from Cloudflare"
  echo "default 0;"
  sed 's/.*/& 1;/' <<<"$ranges"
} > "$dir/cloudflare-geo.conf"

nginx -t
nginx -s reload 2>/dev/null || systemctl reload nginx
echo "Cloudflare ranges: $(wc -l <<<"$ranges")"
